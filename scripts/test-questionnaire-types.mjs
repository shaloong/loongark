import assert from "node:assert/strict";
import { questionnaireValue, questionError, questionnaireFormEntries, renderQuestionControl, createQuestionnaireValidationController } from "../packages/kit/dist/index.js";
const n = {id:"n",label:"Number",type:"number",min:0,max:10,step:.1,required:true};
for (const value of ["", "Infinity", "0x10", "11", "-.1", ".15"]) assert.ok(questionError(n,{n:value}), value);
for (const value of ["0", ".3", "1e0", "10"]) assert.equal(questionError(n,{n:value}), "", value);
const d = {id:"d",label:"Date",type:"date",min:"2024-01-01",max:"2024-12-31"};
for(const value of ["2024-02-30","2023-02-29","2025-01-01","2024-1-01"]) assert.ok(questionError(d,{d:value}));
assert.equal(questionError(d,{d:"2024-02-29"}),"");
const options=[{value:"a",label:"A"},{value:"b",label:"B"},{value:"x",label:"Disabled",disabled:true}];
const matrix={id:"m",label:"Matrix",type:"matrix",required:true,rows:[{id:"r1",label:"First"},{id:"r2",label:"Second"},{id:"x",label:"Disabled",disabled:true}],options};
assert.deepEqual(questionnaireValue([matrix],{m:{r1:"a",r2:"x",x:"b",stale:"a"}}),{m:{r1:"a"}});
assert.ok(questionError(matrix,{m:{r1:"a"}}));assert.equal(questionError(matrix,{m:{r1:"a",r2:"b"}}),"");
const rank={id:"rank",label:"Rank",type:"ranking",options};
assert.deepEqual(questionnaireValue([rank],{rank:["b","x","b","stale"]}),{rank:["b","a"]});
assert.deepEqual(questionnaireValue([rank],{}),{rank:["a","b"]});
assert.deepEqual(questionnaireFormEntries({m:{r1:"a",r2:"b"},rank:["b","a"],text:"value"}),[["m[r1]","a"],["m[r2]","b"],["rank","b"],["rank","a"],["text","value"]]);
assert.throws(()=>questionnaireValue([{...matrix,rows:[{id:"same"},{id:"same"}]}],{}),/row ids/);
assert.throws(()=>questionnaireValue([{...n,step:0}],{}),/positive/);
const html=renderQuestionControl({...matrix,label:'<script>'},{m:{r1:"a"}},'error"id',false);assert.ok(html.includes('name="m[r1]"'));assert.ok(html.includes('error&quot;id'));assert.ok(html.includes(' disabled'));
let snapshot;
const q={...matrix,validateAsync:async (answer,value)=>{snapshot=value;assert.ok(Object.isFrozen(answer));assert.ok(Object.isFrozen(value));return undefined;}};
const controller=createQuestionnaireValidationController(()=>{});controller.sync([q],{m:{r1:"a",r2:"b"}},"m",false);
assert.deepEqual(await controller.run([q],{m:{r1:"a",r2:"b"}}),{value:{m:{r1:"a",r2:"b"}}});assert.ok(snapshot);controller.dispose();
console.log("复杂问卷数值/日期边界、矩阵归一化、排序协调、表单序列化及冻结异步快照通过。");

const rankHtml=renderQuestionControl({...rank,rankingLabels:{handle:'Reorder "item"',instructions:'Press <Enter>'}},{rank:['b','a']},'desc error',true);
assert.ok(rankHtml.includes('data-key="b"'));
assert.ok(rankHtml.includes('aria-describedby="desc error desc-rank-instructions"'));
assert.ok(rankHtml.includes('Reorder &quot;item&quot;: B'));
assert.ok(rankHtml.includes('Press &lt;Enter&gt;'));
assert.ok(rankHtml.includes('aria-live="polite"'));
assert.equal((rankHtml.match(/data-question-control="rank-drag"/g)??[]).length,2);
assert.equal((rankHtml.match(/name="rank"/g)??[]).length,2);
